package Bitwise;

public class doubleTheNumber {
    public static void main(String[] args) {
        int a=10;
        int b=a<<2; // this one left shift can double the number,you can say square the number.
        // agar maine 2 baar left shift kr deya toh it voh double ka double means quadratic ho jayega
        System.out.println(b);
    }
}
